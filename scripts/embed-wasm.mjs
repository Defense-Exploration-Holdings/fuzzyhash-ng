// Usage: node scripts/embed-wasm.mjs <in.wasm> <out.js>
// Emits an ES module exporting the wasm bytes as a base64 string plus a decoder.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: embed-wasm.mjs <in.wasm> <out.js>');
  process.exit(2);
}
const b64 = readFileSync(input).toString('base64');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// SPDX-License-Identifier: MIT
// GENERATED by scripts/embed-wasm.mjs. Do not edit or commit.
const b64 = '${b64}';

export function wasmBytes() {
  if (typeof Buffer !== 'undefined') return new Uint8Array(Buffer.from(b64, 'base64'));
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
`,
);
console.log(`embedded ${input} -> ${output}`);
